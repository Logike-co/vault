El programa es un desarrollo del [DRAKON Editor de Stepan Mitkin](https://drakon.su/drakon_editor "drakon_editor") versión 1.26. El autor amplió la lista de iconos compatibles y agregó nuevas propiedades de gráfico. El programa le permite crear bocetos listos para usar para el entorno de programación Arduino IDE sin tener que ajustar el código generado.

"DrakonBar" se utiliza con éxito en los entrenamientos de círculos y clubes del Parque de las Ciencias y las Artes Sirius en Sochi. La simplicidad y concisión de los diagramas del lenguaje DRAGON permite a los estudiantes de primaria crear programas para placas de microcontrolador Arduino.

