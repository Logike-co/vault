Requisitos previos para utilizar el editor "DrakonBar" para crear bocetos:

1. El intérprete TCL debe ser la versión 8.6.8 o superior.
    
2. Se debe tener instalado el IDE de Arduino, versión no inferior a 1.8.5.
    

El editor se puede utilizar para desarrollo y pruebas en paralelo en varias plataformas de software; por ejemplo, puede trabajar en paralelo en Arduino IDE y Processing IDE.

